"""Build sql/orders.duckdb from a fixed seed. Synthetic, course-authored data.

Run from the repository root:  python sql/build_db.py
Re-running replaces the file and gives the same rows every time.
"""
from __future__ import annotations

import random
from datetime import date, timedelta
from pathlib import Path

import duckdb
import pandas as pd

SEED = 20261006
N_CUSTOMERS = 300
N_ORDERS = 100_000
REGIONS = ["North", "South", "East", "West"]
SEGMENTS = ["retail", "wholesale", "online"]
STATUSES = ["complete"] * 17 + ["cancelled"] * 2 + ["pending"]
N_PRODUCTS = 120

HERE = Path(__file__).resolve().parent
DB = HERE / "orders.duckdb"
COLUMNS = HERE.parent / "generated" / "sql_columns.txt"


def build(db_path: Path = DB) -> dict[str, int]:
    rng = random.Random(SEED)
    if db_path.exists():
        db_path.unlink()
    con = duckdb.connect(str(db_path))
    con.execute((HERE / "schema.sql").read_text())

    customers = [
        (cid, f"Customer {cid:04d}", rng.choice(REGIONS), rng.choice(SEGMENTS))
        for cid in range(1, N_CUSTOMERS + 1)
    ]
    prices = {pid: round(rng.uniform(2, 80), 2) for pid in range(1, N_PRODUCTS + 1)}
    start = date(2025, 1, 1)
    orders, lines = [], []
    for oid in range(1, N_ORDERS + 1):
        cid = rng.randint(1, N_CUSTOMERS)
        day = start + timedelta(days=rng.randint(0, 364))
        orders.append((oid, cid, day, rng.choice(STATUSES)))
        for line_no in range(1, rng.randint(1, 4) + 1):
            pid = rng.randint(1, N_PRODUCTS)
            lines.append((oid, line_no, pid, rng.randint(1, 12), prices[pid]))

    frames = {
        "customers": pd.DataFrame(customers, columns=["customer_id", "name", "region", "segment"]),
        "orders": pd.DataFrame(orders, columns=["order_id", "customer_id", "order_date", "status"]),
        "line_items": pd.DataFrame(
            lines, columns=["order_id", "line_no", "product_id", "quantity", "unit_price"]
        ),
    }
    for table, frame in frames.items():
        con.register("frame", frame)
        con.execute(f"INSERT INTO {table} BY NAME SELECT * FROM frame")
        con.unregister("frame")
    counts = {
        t: con.execute(f"SELECT count(*) FROM {t}").fetchone()[0]
        for t in ("customers", "orders", "line_items")
    }
    lines_out = ["# GENERATED by sql/build_db.py. Do not edit; re-run the script.", ""]
    for table in ("customers", "orders", "line_items"):
        for name, dtype, *_ in con.execute(f"DESCRIBE {table}").fetchall():
            lines_out.append(f"{table}.{name}: {dtype}")
    COLUMNS.write_text("\n".join(lines_out) + "\n", encoding="utf-8")
    con.close()
    return counts


if __name__ == "__main__":
    for table, n in build().items():
        print(f"{table}: {n:,} rows")
    print(f"written: sql/{DB.name} and generated/{COLUMNS.name}")
